#pragma once

namespace pier::dimensions
{
    /**
     * 自定义维度的竖直范围 —— **唯一的一份**。
     *
     * 走引擎原生数据驱动维度之后，这个范围有两个消费者：
     *
     *   1. `Dimension` 构造函数里的 `DimensionArguments{..., {minY, maxY}, ...}`
     *      —— 决定服务端实际生成、存储、发送多少个子区块；
     *   2. `DimensionDefinitionGroup::DimensionDefinition{minY, maxY, ...}`
     *      —— 这条定义会被 `DimensionDataPacket` 整个发给客户端，决定客户端为
     *      这个维度分配多高的区块缓冲、以及它会向服务端请求哪些子区块索引。
     *
     * 两者只要对不上，客户端就会收到落在自己缓冲之外的子区块 —— 表现是进维度
     * 加载完直接闪退。所以这两处**必须**读同一个常量，谁都不许从配置或 NBT 里
     * 另外读一份。
     *
     * 真要支持「每个维度不同高度」的话，正确做法是让上面两个消费者从**同一份
     * payload** 取值（payload 在 `addDimension` 里已经先于注册准备好，顺序上是
     * 可行的），而不是一边读 NBT、一边用写死的常量。
     */

    /**
     * 底部为什么是 -512 而不是 -64
     * ------------------------------
     * 因为**客户端就是这么假定的，而且不听我们的**。实测三次：
     *
     *   我们在 DimensionDefinition 里发的      客户端请求的子区块 y
     *   -64..320  （高 384）                    -32 .. -24
     *    0..384   （高 384，底部变了）          -32 .. -24
     *    0..256   （高 256，高度也变了）        -32 .. -24
     *
     * 两个自变量都动过，输出一个数都没变 —— 客户端在自定义维度里根本没用我们
     * 发过去的几何信息，它退回到「最大可能世界」，底部恒定取子区块 -32，也就
     * 是 y = -512。而服务端按 -64 校验，于是每一个子区块请求都被判
     * IndexOutOfBounds，方块数据一块都过不去（实测 13878/13878 全越界）。
     *
     * 对照组：主世界同一个客户端请求 -4..4，全部成功 —— 原版维度它自己认识，
     * 不需要我们告诉它。
     *
     * 所以把服务端搬过去和它对齐：底部改成 -512（= 子区块 -32）。每列的**请求
     * 条数**是服务端算的（实测是「最高非空气子区块 - 底部」），底部一致之后这
     * 个数会自动涨到覆盖地表，客户端也就会把地形那一段要过去。
     *
     * 顶部保持 320 不动，所以维度总高变成 832 格 = 52 个子区块。
     *
     * 代价与风险：
     *   - 每列多出 28 个子区块。它们是纯空气，调色板只有一项，序列化后很小；
     *     但内存里确实多占一些。
     *   - 引擎对维度高度有没有上限没能从头文件里确认。**如果开服时报错或维度
     *     建不出来，把这里改回 -64 即可回到原状**（那样区块依然显示不出来，但
     *     不会更糟）。
     *   - 已有存档的区块是按 -64 的底部写的，换底部之后对不上。用这个高度建过
     *     的测试世界建议删掉重建。
     */
    inline constexpr int kWorldMinY = -512;
    inline constexpr int kWorldMaxY = 320;

    /**
     * 基岩层所在的 y。
     *
     * 维度底部下移到 -512 之后，如果还把基岩放在缓冲区索引 0（也就是
     * y=-512），上面到地表之间会被填土填掉 576 层 —— 又费内存又没意义。所以基
     * 岩仍然放在 y=-64，它下面那 448 格全是空气，玩家看到的世界和以前**完全一
     * 样**。
     */
    inline constexpr int kBedrockY = -64;

    static_assert(kWorldMinY % 16 == 0, "维度底部必须对齐到子区块边界");
    static_assert(kWorldMaxY % 16 == 0, "维度顶部必须对齐到子区块边界");
    static_assert(kWorldMinY < kWorldMaxY, "维度高度范围为空");
    static_assert(kWorldMinY < kBedrockY && kBedrockY < kWorldMaxY, "基岩层必须在维度范围内");
} // namespace pier::dimensions
